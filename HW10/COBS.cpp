//=============================================================================
// Реализация алгоритма COBS
//=============================================================================

#include "COBS.h"
#include <cstring>  // Для memcpy (опционально)

//-----------------------------------------------------------------------------
// ФУНКЦИЯ: COBSEncode
// Назначение: Кодирование входных данных с исключением зарезервированного байта
//-----------------------------------------------------------------------------
unsigned COBSEncode(const unsigned char* src, unsigned len, 
                    unsigned char* dst, unsigned char reserved) {
    // -------------------------------------------------------------------------
    // ГРАНИЧНЫЙ СЛУЧАЙ: пустые входные данные
    // -------------------------------------------------------------------------
    // Если вход пустой, возвращаем 0 — нет данных для кодирования
    if (len == 0) return 0;
    
    // -------------------------------------------------------------------------
    // ИНИЦИАЛИЗАЦИЯ УКАЗАТЕЛЕЙ И СЧЁТЧИКОВ
    // -------------------------------------------------------------------------
    unsigned read_index = 0;    // Позиция чтения во входном буфере (src)
    unsigned write_index = 1;   // Позиция записи в выходном буфере (dst)
                                // Начинаем с 1, т.к. 0-й байт зарезервирован под код
    unsigned code_index = 0;    // Индекс байта, куда запишем код длины текущего блока
    unsigned char code = 1;     // Счётчик длины текущего блока (начинаем с 1)
    
    // -------------------------------------------------------------------------
    // ОСНОВНОЙ ЦИКЛ: обработка входных данных побайтово
    // -------------------------------------------------------------------------
    while (read_index < len) {
        
        // ---------------------------------------------------------------------
        // СЛУЧАЙ 1: Найден зарезервированный байт
        // ---------------------------------------------------------------------
        // Этот байт нужно "спрятать" — он не должен попасть в выходные данные
        if (src[read_index] == reserved) {
            // Записываем код длины текущего блока в соответствующую позицию
            // Код = количество байтов в блоке + 1 (сам код тоже считается)
            dst[code_index] = code;
            
            // Сбрасываем счётчик для нового блока
            code = 1;
            
            // Запоминаем позицию для кода следующего блока
            code_index = write_index++;
            
            // Пропускаем зарезервированный байт — он НЕ копируется в dst!
            read_index++;
        }
        // ---------------------------------------------------------------------
        // СЛУЧАЙ 2: Обычный байт (не зарезервированный)
        // ---------------------------------------------------------------------
        else {
            // Копируем байт в выходной буфер
            dst[write_index++] = src[read_index++];
            
            // Увеличиваем счётчик длины текущего блока
            code++;
            
            // -----------------------------------------------------------------
            // ПРОВЕРКА: достигнут максимальный размер блока (254 данных + 1 код = 255)
            // -----------------------------------------------------------------
            // Если code == 0xFF (255), значит блок переполнился
            // Нужно завершить текущий блок и начать новый
            if (code == 0xFF) {
                // Записываем код завершённого блока
                dst[code_index] = code;
                
                // Сбрасываем для нового блока
                code = 1;
                code_index = write_index++;
            }
        }
    }
    
    // -------------------------------------------------------------------------
    // ОБРАБОТКА ПОСЛЕДНЕГО БЛОКА
    // -------------------------------------------------------------------------
    // После выхода из цикла остался необработанный последний блок
    // Записываем его код
    dst[code_index] = code;
    
    // -------------------------------------------------------------------------
    // ДОБАВЛЕНИЕ ЗАВЕРШАЮЩЕГО МАРКЕРА
    // -------------------------------------------------------------------------
    // Байт 0 в конце сигнализирует декодеру о конце данных
    // Это важно для корректного декодирования, особенно если последний блок
    // не заканчивался зарезервированным байтом
    dst[write_index] = 0;
    
    // Возвращаем общую длину закодированных данных
    // +1 для завершающего нуля
    return write_index + 1;
}

//-----------------------------------------------------------------------------
// ФУНКЦИЯ: COBSDecode
// Назначение: Восстановление исходных данных из COBS-кодированных
//-----------------------------------------------------------------------------
unsigned COBSDecode(const unsigned char* src, unsigned len, 
                    unsigned char* dst, unsigned char reserved) {
    // -------------------------------------------------------------------------
    // ГРАНИЧНЫЙ СЛУЧАЙ: пустые входные данные
    // -------------------------------------------------------------------------
    if (len == 0) return 0;
    
    // -------------------------------------------------------------------------
    // ИНИЦИАЛИЗАЦИЯ УКАЗАТЕЛЕЙ
    // -------------------------------------------------------------------------
    unsigned read_index = 0;    // Позиция чтения во входном (закодированном) буфере
    unsigned write_index = 0;   // Позиция записи в выходном (декодированном) буфере
    unsigned char code;         // Код длины текущего блока
    
    // -------------------------------------------------------------------------
    // ОСНОВНОЙ ЦИКЛ: обработка закодированных блоков
    // -------------------------------------------------------------------------
    while (read_index < len) {
        
        // ---------------------------------------------------------------------
        // ШАГ 1: Чтение кода длины блока
        // ---------------------------------------------------------------------
        code = src[read_index];
        
        // ---------------------------------------------------------------------
        // ПРОВЕРКА: маркер конца данных
        // ---------------------------------------------------------------------
        // Байт 0 означает конец закодированных данных
        // Это искусственный маркер, добавленный при кодировании
        if (code == 0) break;
        
        // Переходим к первому байту данных блока
        read_index++;
        
        // ---------------------------------------------------------------------
        // ШАГ 2: Копирование данных блока
        // ---------------------------------------------------------------------
        // Копируем (code - 1) байтов, т.к. один байт — это сам код
        for (unsigned char i = 1; i < code; i++) {
            // Проверка выхода за границы входного буфера
            if (read_index < len) {
                dst[write_index++] = src[read_index++];
            }
        }
        
        // ---------------------------------------------------------------------
        // ШАГ 3: Восстановление зарезервированного байта (если нужно)
        // ---------------------------------------------------------------------
        // Если блок был короче максимального (255) и это не последний блок,
        // значит он заканчивался зарезервированным байтом — нужно его вставить
        if (code < 0xFF && read_index < len && src[read_index] != 0) {
            // Вставляем зарезервированный байт на его исходное место
            dst[write_index++] = reserved;
        }
    }
    
    // Возвращаем длину восстановленных (исходных) данных
    return write_index;
}

//-----------------------------------------------------------------------------
// ФУНКЦИЯ: check
// Назначение: Проверка отсутствия зарезервированного байта в данных
//-----------------------------------------------------------------------------
bool check(const unsigned char* data, unsigned len, unsigned char reserved) {
    // Линейный поиск зарезервированного байта во всём массиве
    for (unsigned i = 0; i < len; i++) {
        // Если нашли запрещённый байт — проверка не пройдена
        if (data[i] == reserved) {
            return false;
        }
    }
    // Если цикл завершился без находок — байт отсутствует, проверка пройдена
    return true;
}
