#include <iostream>
#include <fstream>
#include <vector>
#include <iomanip>
#include "COBS.h"

using namespace std;

//-----------------------------------------------------------------------------
// ФУНКЦИЯ: readFile
// Назначение: Чтение бинарного файла в вектор байтов
//-----------------------------------------------------------------------------
vector<unsigned char> readFile(const string& filename) {
    // Открываем файл в бинарном режиме
    // ios::ate — перемещаем указатель в конец для определения размера
    ifstream file(filename, ios::binary | ios::ate);
    
    // Проверка успешности открытия
    if (!file) {
        cerr << "❌ Ошибка: не удалось открыть файл '" << filename << "'" << endl;
        return {};  // Возвращаем пустой вектор при ошибке
    }
    
    // Определяем размер файла
    // tellg() возвращает текущую позицию указателя (в конце файла)
    streamsize size = file.tellg();
    
    // Возвращаем указатель в начало файла для чтения
    file.seekg(0, ios::beg);
    
    // Создаём буфер нужного размера
    vector<unsigned char> buffer(size);
    
    // Читаем всё содержимое файла в буфер
    // reinterpret_cast нужен для работы с байтами как с char
    if (!file.read(reinterpret_cast<char*>(buffer.data()), size)) {
        cerr << "❌ Ошибка: не удалось прочитать файл" << endl;
        return {};
    }
    
    // Файл автоматически закроется при выходе из функции (RAII)
    return buffer;
}

//-----------------------------------------------------------------------------
// ФУНКЦИЯ: writeFile
// Назначение: Запись вектора байтов в бинарный файл
//-----------------------------------------------------------------------------
bool writeFile(const string& filename, const vector<unsigned char>& data) {
    // Открываем файл для записи в бинарном режиме
    ofstream file(filename, ios::binary);
    
    if (!file) {
        cerr << "❌ Ошибка: не удалось создать файл '" << filename << "'" << endl;
        return false;
    }
    
    // Записываем данные в файл
    file.write(reinterpret_cast<const char*>(data.data()), data.size());
    
    // Файл автоматически закроется, flush() вызовется в деструкторе
    return true;
}

//-----------------------------------------------------------------------------
// ФУНКЦИЯ: printHex
// Назначение: Вывод данных в шестнадцатеричном формате (для отладки)
//-----------------------------------------------------------------------------
void printHex(const unsigned char* data, unsigned len, unsigned maxBytes = 32) {
    // Ограничиваем вывод, чтобы не захламлять консоль
    unsigned toPrint = min(len, maxBytes);
    
    // Устанавливаем формат вывода: шестнадцатеричный, 2 цифры, с ведущим 0
    for (unsigned i = 0; i < toPrint; i++) {
        cout << hex << setw(2) << setfill('0') << static_cast<int>(data[i]) << " ";
        
        // Перенос строки каждые 16 байт для удобства чтения
        if ((i + 1) % 16 == 0) cout << endl;
    }
    
    // Если данных больше, чем отображаем — сообщаем об этом
    if (len > maxBytes) {
        cout << dec << "... (ещё " << (len - maxBytes) << " байт)" << endl;
    }
    // Возвращаем десятичный формат вывода для последующего cout
    cout << dec << endl;
}

//-----------------------------------------------------------------------------
// ФУНКЦИЯ: main
// Назначение: Точка входа, управление тестированием
//-----------------------------------------------------------------------------
int main() {
    // Настройка локали для поддержки русских символов в консоли (опционально)
    // setlocale(LC_ALL, "Russian");
    
    cout << "=== Алгоритм COBS: Кодирование/Декодирование ===" << endl << endl;
    
    // -------------------------------------------------------------------------
    // ШАГ 1: Выбор режима работы
    // -------------------------------------------------------------------------
    cout << "Выберите режим:" << endl;
    cout << "  e — кодирование (encoding)" << endl;
    cout << "  d — декодирование (decoding)" << endl;
    cout << "> ";
    
    char mode;
    cin >> mode;
    
    // Проверка корректности ввода
    if (mode != 'e' && mode != 'd') {
        cerr << "❌ Ошибка: неверный режим. Используйте 'e' или 'd'" << endl;
        return 1;
    }
    
    // -------------------------------------------------------------------------
    // ШАГ 2: Ввод имён файлов
    // -------------------------------------------------------------------------
    string inputFile, outputFile;
    cout << "Введите имя входного файла: ";
    cin >> inputFile;
    cout << "Введите имя выходного файла: ";
    cin >> outputFile;
    
    // -------------------------------------------------------------------------
    // ШАГ 3: Чтение входного файла
    // -------------------------------------------------------------------------
    auto inputData = readFile(inputFile);
    if (inputData.empty()) {
        // readFile уже вывел сообщение об ошибке
        return 1;
    }
    
    cout << "\n📊 Статистика:" << endl;
    cout << "  Размер входных данных: " << inputData.size() << " байт" << endl;
    
    // -------------------------------------------------------------------------
    // ШАГ 4: Выполнение выбранной операции
    // -------------------------------------------------------------------------
    if (mode == 'e') {
        // ==================== КОДИРОВАНИЕ ====================
        
        // Выделяем буфер для закодированных данных
        // Размер: исходный + максимум 0.4% накладных расходов + 1 для маркера
        vector<unsigned char> encodedData(inputData.size() + inputData.size() / 254 + 1);
        
        // Вызываем функцию кодирования
        unsigned encodedLen = COBSEncode(
            inputData.data(),           // указатель на исходные данные
            inputData.size(),           // длина исходных данных
            encodedData.data(),         // указатель на буфер результата
            0                           // зарезервированный байт (по умолчанию 0)
        );
        
        // Вывод статистики кодирования
        cout << "  Размер закодированных данных: " << encodedLen << " байт" << endl;
        cout << "  Накладные расходы: " 
             << (100.0 * (encodedLen - inputData.size()) / inputData.size()) 
             << "%" << endl;
        
        // Вывод первых байтов для визуальной проверки
        cout << "\n🔍 Первые байты закодированных данных (hex):" << endl;
        printHex(encodedData.data(), encodedLen);
        
        // -----------------------------------------------------------------
        // ПРОВЕРКА КОРРЕКТНОСТИ: байт 0 не должен встречаться в данных
        // -----------------------------------------------------------------
        // Исключаем последний байт (завершающий маркер 0) из проверки
        if (check(encodedData.data(), encodedLen - 1, 0)) {
            cout << "✅ Проверка пройдена: байт 0 отсутствует в данных" << endl;
        } else {
            cout << "❌ ОШИБКА: байт 0 найден в закодированных данных!" << endl;
            return 1;
        }
        
        // -----------------------------------------------------------------
        // ШАГ 5: Сохранение результата в файл
        // -----------------------------------------------------------------
        // Обрезаем вектор до фактической длины закодированных данных
        encodedData.resize(encodedLen);
        
        if (writeFile(outputFile, encodedData)) {
            cout << "✅ Данные успешно сохранены в файл: " << outputFile << endl;
        }
        
    } else {
        // ==================== ДЕКОДИРОВАНИЕ ====================
        
        // Выделяем буфер для декодированных данных
        // Декодированные данные не могут быть длиннее закодированных
        vector<unsigned char> decodedData(inputData.size());
        
        // Вызываем функцию декодирования
        unsigned decodedLen = COBSDecode(
            inputData.data(),           // указатель на закодированные данные
            inputData.size(),           // длина закодированных данных
            decodedData.data(),         // указатель на буфер результата
            0                           // зарезервированный байт
        );
        
        // Вывод статистики декодирования
        cout << "  Размер декодированных данных: " << decodedLen << " байт" << endl;
        
        // Вывод первых байтов для визуальной проверки
        cout << "\n🔍 Первые байты декодированных данных (hex):" << endl;
        printHex(decodedData.data(), decodedLen);
        
        // -----------------------------------------------------------------
        // ШАГ 5: Сохранение результата в файл
        // -----------------------------------------------------------------
        decodedData.resize(decodedLen);
        
        if (writeFile(outputFile, decodedData)) {
            cout << "✅ Данные успешно сохранены в файл: " << outputFile << endl;
        }
    }
    
    // -------------------------------------------------------------------------
    // ШАГ 6: ДЕМОНСТРАЦИОННЫЙ ТЕСТ на простом примере
    // -------------------------------------------------------------------------
    cout << "\n=== Демонстрационный тест ===" << endl;
    
    // Тестовые данные с зарезервированными байтами (0)
    const char* testStr = "Hello\0World\0Test";
    unsigned testLen = 17;  // Включая два байта 0
    
    cout << "Исходные данные (" << testLen << " байт):" << endl;
    printHex(reinterpret_cast<const unsigned char*>(testStr), testLen);
    
    // Кодирование
    vector<unsigned char> testEncoded(testLen + 10);  // +запас для кодов
    unsigned encodedLen = COBSEncode(
        reinterpret_cast<const unsigned char*>(testStr), 
        testLen, 
        testEncoded.data()
    );
    
    cout << "Закодированные данные (" << encodedLen << " байт):" << endl;
    printHex(testEncoded.data(), encodedLen);
    
    // Декодирование
    vector<unsigned char> testDecoded(testLen);
    unsigned decodedLen = COBSDecode(
        testEncoded.data(), 
        encodedLen, 
        testDecoded.data()
    );
    
    cout << "Декодированные данные (" << decodedLen << " байт):" << endl;
    printHex(testDecoded.data(), decodedLen);
    
    // -----------------------------------------------------------------
    // ФИНАЛЬНАЯ ПРОВЕРКА: побайтовое сравнение исходных и восстановленных
    // -----------------------------------------------------------------
    if (decodedLen == testLen && 
        memcmp(testStr, testDecoded.data(), testLen) == 0) {
        cout << "✅ ТЕСТ ПРОЙДЕН: данные восстановлены бит-в-бит!" << endl;
    } else {
        cout << "❌ ТЕСТ НЕ ПРОЙДЕН: расхождение в данных!" << endl;
        return 1;
    }
    
    cout << "\n=== Работа завершена успешно ===" << endl;
    return 0;
}
