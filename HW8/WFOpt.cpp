// Оптимизированная версия алгоритма Вагнера-Фишера
// Использует O(N) памяти вместо O(M×N)

#include "WFOpt.h"
#include <string>
#include <vector>
#include <algorithm>

using namespace std;

int Distance(const char* s, const char* t) {
    // Преобразуем C-строки в string для удобства
    string ss = s;
    string tt = t;
    
    int len_s = ss.length();
    int len_t = tt.length();
    
    // Базовые случаи
    if (len_s == 0) return len_t;
    if (len_t == 0) return len_s;
    
    // Создаем два массива для хранения текущей и предыдущей строки
    // Используем vector для автоматического управления памятью
    vector<int> p1(len_t + 1);  // предыдущая строка
    vector<int> p2(len_t + 1);  // текущая строка
    
    // Инициализируем первую строку (как в полной версии)
    for (int j = 0; j <= len_t; j++) {
        p1[j] = j;
    }
    
    // Заполняем матрицу построчно
    for (int i = 1; i <= len_s; i++) {
        // Первый элемент текущей строки
        p2[0] = i;
        
        // Заполняем остальные элементы строки
        for (int j = 1; j <= len_t; j++) {
            // Стоимость замены: 0 если символы равны, 1 иначе
            int cost = (ss[i-1] == tt[j-1]) ? 0 : 1;
            
            // Вычисляем минимальное расстояние
            p2[j] = min({
                p1[j] + 1,      // удаление
                p2[j-1] + 1,    // вставка
                p1[j-1] + cost  // замена
            });
        }
        
        // Меняем массивы местами
        // Теперь p1 содержит текущую строку для следующей итерации
        swap(p1, p2);
    }
    
    // Результат находится в последнем элементе предыдущей строки
    return p1[len_t];
}