//=============================================================================
// Модуль: WFOpt (Wagner-Fischer Optimized)
// Тема: Оптимизированная версия алгоритма Вагнера-Фишера
// Цель: Вычисление редакционного расстояния с использованием O(N) памяти
//       вместо O(M×N) в полной версии
//=============================================================================

// Заголовочные файлы
#include "WFOpt.h"      // Объявление функции Distance
#include <string>       // std::string для работы со строками
#include <vector>       // std::vector для динамических массивов
#include <algorithm>    // std::min для поиска минимума из трёх значений

using namespace std;

//=============================================================================
// ФУНКЦИЯ: Distance
// Назначение: Вычисление расстояния Левенштейна между двумя строками
// Параметры:
//   s, t — входные C-строки (нуль-терминированные массивы char)
// Возвращает: минимальное количество операций (вставка, удаление, замена)
//             для преобразования строки s в строку t
// Сложность:
//   - Время: O(M×N), где M = len(s), N = len(t)
//   - Память: O(N) — храним только две строки матрицы вместо всей
// Алгоритм "на пальцах":
//   1. Строим матрицу, где cell[i][j] = расстояние между s[0..i) и t[0..j)
//   2. Базовые случаи: пустая строка → расстояние = длина другой строки
//   3. Рекуррентная формула:
//      cell[i][j] = min(
//          cell[i-1][j] + 1,           // удаление s[i-1]
//          cell[i][j-1] + 1,           // вставка t[j-1]
//          cell[i-1][j-1] + cost       // замена или совпадение
//      )
//      где cost = 0 если s[i-1]==t[j-1], иначе 1
//   4. ОПТИМИЗАЦИЯ: для вычисления строки i нужны только строки i и i-1
//      → храним только две строки, меняем их местами после каждой итерации
//=============================================================================
int Distance(const char* s, const char* t) {
    // -------------------------------------------------------------------------
    // ШАГ 0: Подготовка данных
    // -------------------------------------------------------------------------
    // Преобразуем C-строки в std::string для удобства работы
    // Это позволяет использовать .length(), оператор [], и т.д.
    string ss = s;  // Копирование: O(M) по времени и памяти
    string tt = t;  // Копирование: O(N) по времени и памяти
    
    int len_s = ss.length();  // Длина первой строки
    int len_t = tt.length();  // Длина второй строки
    
    // -------------------------------------------------------------------------
    // ШАГ 1: Обработка граничных случаев
    // -------------------------------------------------------------------------
    // Если одна из строк пустая, расстояние равно длине другой строки
    // (нужно вставить/удалить все символы)
    if (len_s == 0) return len_t;  // s пустая → нужно вставить все символы t
    if (len_t == 0) return len_s;  // t пустая → нужно удалить все символы s
    
    // -------------------------------------------------------------------------
    // ШАГ 2: Выделение памяти для двух строк матрицы
    // -------------------------------------------------------------------------
    // Используем vector вместо сырых массивов по причинам:
    // 1. Автоматическое управление памятью (нет утечек)
    // 2. Безопасность (проверка границ в отладочном режиме)
    // 3. Удобство (можно использовать swap, size(), и т.д.)
    
    // p1 — "предыдущая" строка матрицы (инициализируется базовыми значениями)
    // p2 — "текущая" строка (вычисляется на каждой итерации)
    // Размер: len_t + 1, потому что индексы от 0 до len_t включительно
    vector<int> p1(len_t + 1);  // Изначально заполнен нулями
    vector<int> p2(len_t + 1);  // Изначально заполнен нулями
    
    // -------------------------------------------------------------------------
    // ШАГ 3: Инициализация базовой строки (i = 0)
    // -------------------------------------------------------------------------
    // Когда s пустая (i=0), расстояние до t[0..j) равно j
    // Пример: "" → "abc" требует 3 вставки → расстояние = 3
    for (int j = 0; j <= len_t; ++j) {
        p1[j] = j;  // p1[0]=0, p1[1]=1, p1[2]=2, ...
    }
    // Теперь p1 содержит: [0, 1, 2, 3, ..., len_t]
    
    // -------------------------------------------------------------------------
    // ШАГ 4: Основной цикл — заполнение матрицы построчно
    // -------------------------------------------------------------------------
    // Внешний цикл: перебираем символы строки s (индекс i от 1 до len_s)
    // Внутренний цикл: для каждого i вычисляем всю строку j от 1 до len_t
    for (int i = 1; i <= len_s; ++i) {
        
        // ---------------------------------------------------------------------
        // Подшаг 4.1: Инициализация первого элемента текущей строки
        // ---------------------------------------------------------------------
        // Когда t пустая (j=0), расстояние от s[0..i) до "" равно i
        // Пример: "abc" → "" требует 3 удаления → расстояние = 3
        p2[0] = i;  // Первый столбец каждой строки
        
        // ---------------------------------------------------------------------
        // Подшаг 4.2: Вычисление остальных элементов строки
        // ---------------------------------------------------------------------
        for (int j = 1; j <= len_t; ++j) {
            
            // Стоимость замены: 0 если символы совпадают, 1 если разные
            // ss[i-1] — i-й символ строки s (индексация с 0)
            // tt[j-1] — j-й символ строки t
            // Почему i-1 и j-1? Потому что в матрице индексы сдвинуты на 1
            // (нулевая строка/столбец — для пустых префиксов)
            int cost = (ss[i-1] == tt[j-1]) ? 0 : 1;
            
            // -----------------------------------------------------------------
            // Рекуррентная формула Вагнера-Фишера:
            // -----------------------------------------------------------------
            // Вариант 1: Удаление символа из s
            //   p1[j] + 1 — берём значение из предыдущей строки (i-1, j)
            //   +1 — потому что удаление — это одна операция
            //
            // Вариант 2: Вставка символа в s
            //   p2[j-1] + 1 — берём значение из текущей строки (i, j-1)
            //   +1 — потому что вставка — это одна операция
            //
            // Вариант 3: Замена или совпадение
            //   p1[j-1] + cost — берём значение из диагонали (i-1, j-1)
            //   +cost — 0 если символы совпали (бесплатно), 1 если нужна замена
            //
            // Выбираем минимальное из трёх — это и есть оптимальное расстояние
            // -----------------------------------------------------------------
            p2[j] = min({
                p1[j] + 1,        // удаление
                p2[j-1] + 1,      // вставка
                p1[j-1] + cost    // замена/совпадение
            });
            
            // Примечание: min({...}) — инициализатор-список из C++11
            // Позволяет передать произвольное количество аргументов
        }
        
        // ---------------------------------------------------------------------
        // Подшаг 4.3: Подготовка к следующей итерации — обмен строк
        // ---------------------------------------------------------------------
        // После вычисления строки i:
        // - p2 содержит актуальные значения для строки i
        // - p1 больше не нужен (строка i-1)
        // 
        // Вместо копирования p2 в p1 (O(N) операций) используем swap:
        // - swap(p1, p2) меняет указатели на данные, а не копирует данные
        // - Время: O(1), потому что меняются только внутренние указатели vector
        // - После swap: p1 содержит строку i, p2 — "мусор" (будет перезаписан)
        swap(p1, p2);
        
        // Теперь p1 готов к использованию как "предыдущая строка" на шаге i+1
    }
    
    // -------------------------------------------------------------------------
    // ШАГ 5: Возврат результата
    // -------------------------------------------------------------------------
    // После завершения внешнего цикла:
    // - Мы вычислили все строки от 1 до len_s
    // - Последняя вычисленная строка находится в p1 (после последнего swap)
    // - Ответ — правый нижний угол матрицы: расстояние между s и t
    // - Это элемент с индексом [len_t] в массиве длины len_t+1
    return p1[len_t];
    
    // -------------------------------------------------------------------------
    // ШАГ 6: Автоматическая очистка памяти
    // -------------------------------------------------------------------------
    // Векторы p1 и p2 автоматически освобождают память при выходе из функции
    // благодаря деструктору std::vector — никаких утечек памяти!
}
