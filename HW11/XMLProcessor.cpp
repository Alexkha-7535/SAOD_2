using namespace std;

//-----------------------------------------------------------------------------
// МЕТОД: readFile
// Назначение: Чтение файла в строку
//-----------------------------------------------------------------------------
string XMLProcessor::readFile(const string& filename) {
    // Открываем файл для чтения (текстовый режим)
    ifstream file(filename);
    
    // Проверка: файл открылся?
    if (!file) {
        // Выводим ошибку в stderr (не смешиваем с обычным выводом)
        cerr << "Ошибка: не удалось открыть файл '" << filename << "'" << endl;
        return "";  // Пустая строка сигнализирует об ошибке
    }
    
    // -------------------------------------------------------------------------
    // ЭФФЕКТИВНОЕ ЧТЕНИЕ: istreambuf_iterator
    // -------------------------------------------------------------------------
    // Создаём два итератора:
    // 1. begin — указывает на начало файла
    // 2. end — специальный итератор "конец потока"
    // Конструктор string копирует всё между ними
    string content(
        (istreambuf_iterator<char>(file)),  // Начало: читаем из file
        istreambuf_iterator<char>()          // Конец: достигнут EOF
    );
    
    // Файл автоматически закроется при выходе из функции (деструктор ifstream)
    return content;
}

//-----------------------------------------------------------------------------
// МЕТОД: writeFile
// Назначение: Запись строки в файл
//-----------------------------------------------------------------------------
bool XMLProcessor::writeFile(const string& filename, const string& content) {
    // Открываем файл для записи (перезапишет существующий)
    ofstream file(filename);
    
    if (!file) {
        cerr << "Ошибка: не удалось создать файл '" << filename << "'" << endl;
        return false;
    }
    
    // Записываем содержимое
    file << content;
    
    // file автоматически закроется и flush() вызовется в деструкторе
    return true;
}

//-----------------------------------------------------------------------------
// МЕТОД: fixEmptyArticleTags
// Назначение: Исправление дефекта 1 — пустые теги <article>
//-----------------------------------------------------------------------------
string XMLProcessor::fixEmptyArticleTags(const string& xml) {
    // -------------------------------------------------------------------------
    // РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ: поиск пустых article-тегов
    // -------------------------------------------------------------------------
    // Разбор шаблона:
    //   <article>           — открывающий тег (буквально)
    //   \s*                 — 0 или более пробельных символов (пробел, \t, \n)
    //   ([.,;:!?]*)         — ГРУППА 1: 0 или более знаков препинания
    //                         (захватываем, чтобы сохранить в результате)
    //   \s*                 — 0 или более пробелов после знаков
    //   </article>          — закрывающий тег
    //
    // R"(...)" — raw string literal в C++:
    //   - Не нужно экранировать обратные слеши
    //   - \s остаётся \s, а не превращается в спецсимвол
    //
    // Флаги: std::regex::ECMAScript (по умолчанию) — синтаксис как в ECMAScript
    regex emptyArticleRegex(R"(<article>\s*([.,;:!?]*)\s*</article>)");
    
    // -------------------------------------------------------------------------
    // ЗАМЕНА: удаление тегов с сохранением знаков препинания
    // -------------------------------------------------------------------------
    // $1 — ссылка на первую группу захвата (знаки препинания)
    // Если группа пуста (не было знаков) — вставится пустая строка
    // Результат: <article> . </article> → .
    string result = regex_replace(xml, emptyArticleRegex, "$1");
    
    return result;
}

//-----------------------------------------------------------------------------
// МЕТОД: fixSpacesBeforePunctuation
// Назначение: Исправление дефекта 2 — пробелы перед знаками препинания
//-----------------------------------------------------------------------------
string XMLProcessor::fixSpacesBeforePunctuation(const string& xml) {
    // -------------------------------------------------------------------------
    // РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ: пробел(ы) перед знаком препинания
    // -------------------------------------------------------------------------
    // Разбор шаблона:
    //   (\w)                — ГРУППА 1: один словесный символ (буква/цифра/_)
    //                         (это последний символ слова перед пробелом)
    //   \s+                 — 1 или более пробельных символов (искомая проблема)
    //   ([.,;:!?])          — ГРУППА 2: один знак препинания
    //
    // Почему \w, а не \w+?
    //   - Нам нужен только ПОСЛЕДНИЙ символ слова для "склейки"
    //   - Остальная часть слова остаётся в тексте без изменений
    //   - Это более эффективно, чем захватывать всё слово
    regex spaceBeforePunctRegex(R"((\w)\s+([.,;:!?]))");
    
    // -------------------------------------------------------------------------
    // ЗАМЕНА: удаление пробелов между словом и знаком
    // -------------------------------------------------------------------------
    // $1$2 — склеиваем группу 1 (символ слова) и группу 2 (знак)
    // Результат: "слово ," → "слово,"
    // 
    // Почему это работает для всех вхождений?
    //   - regex_replace по умолчанию заменяет ВСЕ совпадения (global replace)
    //   - Для замены только первого используйте regex_replace(..., ..., ..., 
    //     std::regex_constants::format_first_only)
    string result = regex_replace(xml, spaceBeforePunctRegex, "$1$2");
    
    return result;
}

//-----------------------------------------------------------------------------
// МЕТОД: validateXML
// Назначение: Базовая проверка баланса тегов
//-----------------------------------------------------------------------------
bool XMLProcessor::validateXML(const string& xml) {
    // -------------------------------------------------------------------------
    // РЕГУЛЯРНЫЕ ВЫРАЖЕНИЯ ДЛЯ ПОИСКА ТЕГОВ
    // -------------------------------------------------------------------------
    
    // Открывающий тег: <имя атрибуты="знач"> или <имя/>
    // Разбор:
    //   <                 — символ < (буквально)
    //   (\w+)             — ГРУППА 1: имя тега (1+ словесных символов)
    //   [^>]*             — любые символы кроме > (атрибуты, пробелы)
    //   >                 — закрывающий >
    // 
    // Примеры совпадений: <article>, <bold class="x">, <item/>
    regex openTagRegex(R"(<(\w+)[^>]*>)");
    
    // Закрывающий тег: </имя>
    // Разбор:
    //   </                — символы </ (буквально)
    //   (\w+)             — ГРУППА 1: имя тега
    //   >                 — закрывающий >
    regex closeTagRegex(R"(</(\w+)>)");
    
    // -------------------------------------------------------------------------
    // ПОДСЧЁТ ТЕГОВ С ПОМОЩЬЮ ИТЕРАТОРОВ
    // -------------------------------------------------------------------------
    // sregex_iterator — итератор по всем совпадениям regex в строке
    // 
    // Создаём итераторы для открывающих тегов:
    auto openBegin = sregex_iterator(xml.begin(), xml.end(), openTagRegex);
    auto openEnd = sregex_iterator();  // Специальный "конец" итератор
    
    // И итераторы для закрывающих:
    auto closeBegin = sregex_iterator(xml.begin(), xml.end(), closeTagRegex);
    auto closeEnd = sregex_iterator();
    
    // distance() считает количество шагов между итераторами
    // Для input_iterator это O(N), но для наших небольших файлов — приемлемо
    size_t openCount = distance(openBegin, openEnd);
    size_t closeCount = distance(closeBegin, closeEnd);
    
    // -------------------------------------------------------------------------
    // ПРОВЕРКА: сбалансированы ли теги?
    // -------------------------------------------------------------------------
    // Простейшая эвристика: количество открывающих = количеству закрывающих
    // 
    // ОГРАНИЧЕНИЯ ЭТОЙ ПРОВЕРКИ:
    //   - Не проверяет правильность вложенности: <a><b></a></b> пройдёт проверку
    //   - Не проверяет соответствие имён: <a></b> пройдёт, если по одному каждого
    //   - Не учитывает самозакрывающиеся теги: <br/> считается за открывающий
    // 
    // Для продакшена используйте полноценный XML-парсер!
    return openCount == closeCount;
}

//-----------------------------------------------------------------------------
// МЕТОД: findLeafTags
// Назначение: Поиск тегов без вложенных тегов
//-----------------------------------------------------------------------------
vector<string> XMLProcessor::findLeafTags(const string& xml) {
    vector<string> leafTags;  // Результат: список найденных листовых тегов
    
    // -------------------------------------------------------------------------
    // РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ: листовой тег
    // -------------------------------------------------------------------------
    // Разбор шаблона:
    //   <(\w+)              — ГРУППА 1: имя открывающего тега
    //   [^>]*               — атрибуты (любые символы кроме >)
    //   >                   — закрывающий > открывающего тега
    //   ([^<>]*)            — ГРУППА 2: содержимое (любые символы кроме < и >)
    //                         Это гарантирует отсутствие вложенных тегов!
    //   </\1>               — закрывающий тег с ОБРАТНОЙ ССЫЛКОЙ \1
    //                         \1 означает "то же имя тега, что в группе 1"
    //                         Это гарантирует, что <a>...</a>, а не <a>...</b>
    //
    // Примеры совпадений:
    //   <bold>А</bold>        — листовой
    //   <article>Текст</article> — листовой  
    //   <letter><bold>А</bold></letter> — не листовой (есть вложенный <bold>)
    regex leafTagRegex(R"(<(\w+)[^>]*>([^<>]*)</\1>)");
    
    // -------------------------------------------------------------------------
    // СБОР ВСЕХ СОВПАДЕНИЙ
    // -------------------------------------------------------------------------
    // Проходим по всем совпадениям с помощью итератора
    auto begin = sregex_iterator(xml.begin(), xml.end(), leafTagRegex);
    auto end = sregex_iterator();  // Маркер конца
    
    for (auto it = begin; it != end; ++it) {
        // it->str() возвращает ВЕСЬ совпавший текст (не только группы)
        // Например: "<bold>А</bold>", а не только "А"
        leafTags.push_back(it->str());
    }
    
    return leafTags;
}
