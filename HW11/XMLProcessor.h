//=============================================================================
// Назначение: Обработка XML-файлов с помощью регулярных выражений
// Задачи: Поиск дефектов, исправление, валидация структуры
//=============================================================================

#ifndef XMLPROCESSOR_H
#define XMLPROCESSOR_H

#include <string>      // std::string для работы с текстом
#include <vector>      // std::vector для коллекций результатов
#include <regex>       // std::regex для регулярных выражений (C++11)
#include <fstream>     // std::ifstream/ofstream для работы с файлами

/**
 * Класс для обработки XML-документов
 * 
 * Предоставляет статические методы для:
 * - Чтения/записи файлов
 * - Поиска и исправления дефектов с помощью регулярных выражений
 * - Базовой валидации структуры XML
 * - Анализа тегов
 * 
 * Все методы static — класс не хранит состояние, только функции
 */
class XMLProcessor {
public:
    // -------------------------------------------------------------------------
    // РАБОТА С ФАЙЛАМИ
    // -------------------------------------------------------------------------
    
    /**
     * Чтение всего содержимого файла в строку
     * @param filename — путь к файлу
     * @return содержимое файла как строка, или пустая строка при ошибке
     * 
     * Особенности:
     * - Использует istreambuf_iterator для эффективного чтения
     * - Автоматически закрывает файл (RAII через ifstream)
     */
    static std::string readFile(const std::string& filename);
    
    /**
     * Запись строки в файл
     * @param filename — путь к файлу
     * @param content — содержимое для записи
     * @return true при успехе, false при ошибке
     */
    static bool writeFile(const std::string& filename, const std::string& content);
    
    // -------------------------------------------------------------------------
    // ИСПРАВЛЕНИЕ ДЕФЕКТОВ
    // -------------------------------------------------------------------------
    
    /**
     * Дефект 1: Удаление пустых тегов <article>
     * 
     * Проблема: Теги <article> могут содержать только пробелы или знаки препинания
     * Решение: Удалить теги форматирования, но сохранить знаки препинания
     * 
     * Пример:
     *   Вход:  <article>   .   </article>
     *   Выход: .
     * 
     * @param xml — исходный XML-текст
     * @return текст с исправленными пустыми тегами
     */
    static std::string fixEmptyArticleTags(const std::string& xml);
    
    /**
     * Дефект 2: Удаление пробелов перед знаками препинания
     * 
     * Проблема: Перед знаками препинания стоят лишние пробелы
     * Решение: Удалить пробелы, сохранив слово и знак
     * 
     * Пример:
     *   Вход:  "слово , ещё текст !"
     *   Выход: "слово, ещё текст!"
     * 
     * @param xml — XML-текст (можно после fixEmptyArticleTags)
     * @return текст с исправленными пробелами
     */
    static std::string fixSpacesBeforePunctuation(const std::string& xml);
    
    // -------------------------------------------------------------------------
    // ВАЛИДАЦИЯ И АНАЛИЗ
    // -------------------------------------------------------------------------
    
    /**
     * Базовая проверка корректности XML
     * 
     * Упрощённая проверка: сравнивает количество открывающих и закрывающих тегов
     * НЕ проверяет: вложенность, атрибуты, корректность имён тегов
     * 
     * @param xml — XML-текст для проверки
     * @return true если количество тегов сбалансировано, false иначе
     */
    static bool validateXML(const std::string& xml);
    
    /**
     * Поиск листовых тегов (тегов без вложенных тегов)
     * 
     * Листовой тег: <tag>текст</tag> без других <...> внутри
     * Примеры листовых: <bold>А</bold>, <article>Текст</article>
     * Пример НЕ листового: <letter><bold>А</bold></letter>
     * 
     * @param xml — XML-текст для анализа
     * @return вектор строк, каждая — полный текст листового тега
     */
    static std::vector<std::string> findLeafTags(const std::string& xml);
};

#endif 
