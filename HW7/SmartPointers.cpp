//=============================================================================
// Проект: SmartPointers
// Тема: Исследование поведения умных указателей в C++
// Цель: Понимание проблем владения массивами и способов их решения
//=============================================================================

// Стандартные библиотеки
#include <iostream>   // cout, endl для вывода на консоль
#include <memory>     // shared_ptr, unique_ptr, default_delete — умные указатели

using namespace std;

//=============================================================================
// КЛАСС: Test
// Назначение: Тестовый класс с "говорящими" конструктором/деструктором
// Особенности:
//   - Конструктор и деструктор выводят сообщения при вызове
//   - Это позволяет визуально отслеживать время жизни объектов
//   - Поле Val используется для проверки корректности доступа к данным
//=============================================================================
class Test {
public:
    int Val; // Публичное поле для хранения тестового значения
    
    // -------------------------------------------------------------------------
    // КОНСТРУКТОР по умолчанию
    // Назначение: Создание объекта и инициализация поля Val
    // Примечание: Сообщение помогает отследить момент создания объекта
    // -------------------------------------------------------------------------
    Test() : Val(0) {  // Инициализация списка: устанавливаем Val = 0
        cout << "  [Test] Конструктор вызван. Объект создан. Val = " << Val << endl;
    }
    
    // -------------------------------------------------------------------------
    // ДЕСТРУКТОР
    // Назначение: Очистка ресурсов при уничтожении объекта
    // Примечание: Автоматически вызывается при выходе объекта из области видимости
    //            или при удалении через delete
    // -------------------------------------------------------------------------
    ~Test() {
        cout << "  [Test] Деструктор вызван. Объект уничтожен. Val = " << Val << endl;
    }
};

//=============================================================================
// ФУНКЦИЯ: main
// Назначение: Демонстрация различных сценариев использования умных указателей
//=============================================================================
int main() {
    // Вывод заголовка для наглядности
    cout << "=== ЧАСТЬ 2: Умные указатели shared_ptr и unique_ptr ===" << endl << endl;
    
    // =========================================================================
    // СЦЕНАРИЙ 1: Проблема shared_ptr с массивами
    // =========================================================================
    // Комментарий: Стандартный shared_ptr<T> использует delete для освобождения
    // памяти. Но для массивов нужно использовать delete[]!
    // Если использовать shared_ptr<Test> для массива Test[3], то:
    //   - Будет вызван деструктор только для ПЕРВОГО элемента
    //   - Остальные 2 элемента утекут (память не будет освобождена)
    //   - Это неопределённое поведение (Undefined Behavior)
    // -------------------------------------------------------------------------
    cout << "--- ПРОБЛЕМА: shared_ptr<Test> sp(new Test[3]) ---" << endl;
    {
        /* 
        // ЗАКОММЕНТИРОВАНО, чтобы не вызывать утечку памяти при выполнении
        shared_ptr<Test> sp(new Test[3]);
        // Ожидается: 3 сообщения о создании, 1 сообщение об уничтожении
        // Реальность: 3 создания, 1 уничтожение → утечка 2 объектов!
        */
        cout << "  (Код закомментирован для предотвращения утечки)" << endl;
        cout << "  Если раскомментировать: создастся 3 объекта, удалится только 1!" << endl;
    }
    cout << "  Конец блока: объекты должны были бы удалиться (но не все)" << endl << endl;
    
    // =========================================================================
    // СЦЕНАРИЙ 2: Решение 1 — специализация shared_ptr для массивов
    // =========================================================================
    // Комментарий: shared_ptr<Test[]> — специальная версия для работы с массивами
    // Особенности:
    //   - Автоматически использует delete[] вместо delete
    //   - Поддерживает оператор [] через метод get()
    //   - Сохраняет все преимущества shared_ptr (подсчёт ссылок, авто-удаление)
    // -------------------------------------------------------------------------
    cout << "--- РЕШЕНИЕ 1: shared_ptr<Test[]> sp(new Test[3]) ---" << endl;
    {
        // Создаём умный указатель на массив из 3 объектов Test
        // shared_ptr<Test[]> автоматически знает, что нужно вызвать delete[]
        shared_ptr<Test[]> sp(new Test[3]);
        
        // Доступ к элементам массива:
        // - У shared_ptr НЕТ оператора operator[]
        // - Метод get() возвращает "сырой" указатель (Test*)
        // - К этому указателю можно применять оператор []
        for (int i = 0; i < 3; ++i) {
            sp.get()[i].Val = (i + 1) * 10;  // Устанавливаем значения: 10, 20, 30
        }
        
        // Выводим установленные значения для проверки
        cout << "  Значения поля Val: ";
        for (int i = 0; i < 3; ++i) {
            cout << sp.get()[i].Val << " ";
        }
        cout << endl;
        
        // При выходе из блока:
        // 1. Счётчик ссылок shared_ptr становится 0
        // 2. Автоматически вызывается delete[] для массива
        // 3. Деструкторы всех 3 объектов вызываются в обратном порядке
    }
    cout << "  Конец блока: все 3 объекта корректно уничтожены" << endl << endl;
    
    // =========================================================================
    // СЦЕНАРИЙ 3: Решение 2 — кастомный удалитель (deleter)
    // =========================================================================
    // Комментарий: Альтернативный способ — передать вторым параметром конструктора
    // функцию-удалитель. default_delete<Test[]> — стандартный удалитель для массивов
    // Преимущества:
    //   - Можно использовать с обычным shared_ptr<Test>
    //   - Гибкость: можно задать любой способ освобождения памяти
    // Недостатки:
    //   - Менее интуитивно, чем shared_ptr<Test[]>
    //   - Нужно помнить о передаче correct deleter
    // -------------------------------------------------------------------------
    cout << "--- РЕШЕНИЕ 2: shared_ptr с default_delete<Test[]> ---" << endl;
    {
        // Конструктор shared_ptr принимает два параметра:
        // 1. Указатель на выделенную память: new Test[3]
        // 2. Удалитель: default_delete<Test[]>() — функция, которая вызовет delete[]
        shared_ptr<Test> sp(new Test[3], default_delete<Test[]>());
        
        // Установка значений (аналогично предыдущему примеру)
        for (int i = 0; i < 3; ++i) {
            sp.get()[i].Val = (i + 1) * 20;  // Значения: 20, 40, 60
        }
        
        cout << "  Значения поля Val: ";
        for (int i = 0; i < 3; ++i) {
            cout << sp.get()[i].Val << " ";
        }
        cout << endl;
    }
    cout << "  Конец блока: все 3 объекта корректно уничтожены" << endl << endl;
    
    // =========================================================================
    // СЦЕНАРИЙ 4: unique_ptr — единственное владение ресурсом
    // =========================================================================
    // Комментарий: unique_ptr гарантирует, что ресурсом владеет только один указатель
    // Особенности:
    //   - Нельзя копировать (только перемещать через std::move)
    //   - Нулевые накладные расходы по сравнению с сырым указателем
    //   - Автоматически вызывает delete[] для unique_ptr<T[]>
    //   - Поддерживает оператор [] напрямую (в отличие от shared_ptr)
    // Когда использовать:
    //   - Когда ресурс не должен передаваться между владельцами
    //   - Для полей классов, где владение явно единственное
    //   - Когда важна максимальная производительность (нет подсчёта ссылок)
    // -------------------------------------------------------------------------
    cout << "--- unique_ptr<Test[]> p(new Test[3]) ---" << endl;
    {
        // Создаём unique_ptr на массив из 3 объектов
        // Тип Test[] указывает, что это массив, поэтому будет использован delete[]
        unique_ptr<Test[]> p(new Test[3]);
        
        // УНИКАЛЬНОЕ ПРЕИМУЩЕСТВО unique_ptr:
        // - Поддерживает оператор [] напрямую: p[i]
        // - Не нужно вызывать get() как в shared_ptr
        for (int i = 0; i < 3; ++i) {
            p[i].Val = (i + 1) * 30;  // Значения: 30, 60, 90
        }
        
        cout << "  Значения поля Val: ";
        for (int i = 0; i < 3; ++i) {
            cout << p[i].Val << " ";  // Прямой доступ через p[i]
        }
        cout << endl;
        
        // ---------------------------------------------------------------------
        // ДЕМОНСТРАЦИЯ МЕТОДА reset()
        // ---------------------------------------------------------------------
        // reset() заменяет управляемый ресурс на новый
        // Старый ресурс автоматически удаляется (если счётчик ссылок = 0)
        cout << "  --------- Демонстрация reset() ---------" << endl;
        
        // Создаём новый массив из 2 объектов
        // Старые 3 объекта будут уничтожены ПЕРЕД созданием новых
        p.reset(new Test[2]);
        
        // Устанавливаем значения для новых объектов
        for (int i = 0; i < 2; ++i) {
            p[i].Val = (i + 1) * 100;  // Значения: 100, 200
        }
        
        cout << "  Новые значения после reset(): ";
        for (int i = 0; i < 2; ++i) {
            cout << p[i].Val << " ";
        }
        cout << endl;
        cout << "  --------- Конец демонстрации ---------" << endl;
        
        // При выходе из блока:
        // - Уникальный владелец (p) выходит из области видимости
        // - Автоматически вызывается delete[] для текущих 2 объектов
        // - Деструкторы вызываются для всех созданных объектов
    }
    cout << "  Конец main(): все объекты успешно уничтожены, утечек нет" << endl;
    
    // =========================================================================
    // ИТОГОВЫЕ ВЫВОДЫ
    // =========================================================================
    cout << "\n=== Ключевые выводы ===" << endl;
    cout << "1. shared_ptr<T> + new T[N] = ОПАСНО (утечка памяти)" << endl;
    cout << "2. shared_ptr<T[]> или shared_ptr<T> + default_delete<T[]> = БЕЗОПАСНО" << endl;
    cout << "3. unique_ptr<T[]> — идеален для единственного владения массивом" << endl;
    cout << "4. Для доступа к элементам:" << endl;
    cout << "   - shared_ptr: используйте .get()[i]" << endl;
    cout << "   - unique_ptr: используйте прямой оператор [i]" << endl;
    cout << "5. reset() позволяет заменить управляемый ресурс с авто-очисткой" << endl;
    
    return 0;
}
