//=============================================================================
// Проект: IntersectList
// Тема: Сравнение эффективности поиска общих элементов в списках
// Подходы: "в лоб" (O(N²)) vs с предобработкой в unordered_set (O(N))
//=============================================================================

// Стандартные библиотеки
#include <iostream>      // cout, cin для ввода-вывода
#include <list>          // std::list — двусвязный список из STL
#include <string>        // std::string для работы со строками
#include <chrono>        // chrono для точного измерения времени выполнения
#include <unordered_set> // std::unordered_set — хеш-таблица для быстрого поиска
#include <cstdlib>       // rand(), srand() для генерации случайных чисел
#include <ctime>         // time() для инициализации генератора случайных чисел
#include <numeric>       // std::accumulate для суммирования результатов

using namespace std;

//=============================================================================
// ФУНКЦИЯ: getRandom
// Назначение: Генерация случайной строки заданной длины
// Параметры:
//   len — желаемая длина строки
// Возвращает: строку, состоящую из случайных символов [0-9a-z]
// Примечание: Используется статический массив символов для экономии памяти
//=============================================================================
string getRandom(int len) {
    // Статический массив допустимых символов
    // static означает, что массив создаётся один раз при первом вызове
    static const char ab[] = "0123456789abcdefghijklmnopqrstuvwxyz";
    
    // Вычисляем длину алфавита (sizeof включает '\0', поэтому вычитаем 1)
    static const int aLen = sizeof(ab) - 1;
    
    // Создаём строку нужной длины, заполненную пробелами
    // string(len, ' ') — конструктор, создающий строку из len копий символа ' '
    string s(len, ' ');
    
    // Заполняем каждый символ строки случайным символом из алфавита
    for (int i = 0; i < len; ++i) {
        // rand() % aLen даёт случайное число от 0 до aLen-1
        // Это индекс в массиве ab, который мы используем для выбора символа
        s[i] = ab[rand() % aLen];
    }
    
    return s; // Возвращаем готовую строку
}

//=============================================================================
// ФУНКЦИЯ: prepareData
// Назначение: Подготовка тестовых данных — двух списков с общими элементами
// Параметры:
//   N — целевой размер каждого списка
//   list1, list2 — выходные списки для заполнения
//   common — список общих элементов, которые будут вставлены в оба списка
// Алгоритм:
//   1. Заполняем каждую половину списка уникальными случайными строками
//   2. Вставляем общие элементы в случайные позиции обоих списков
//=============================================================================
void prepareData(int N, list<string>& list1, list<string>& list2, list<string>& common) {
    // Очищаем списки на случай повторного вызова функции
    common.clear(); 
    list1.clear(); 
    list2.clear();
    
    // -------------------------------------------------------------------------
    // Шаг 1: Заполнение уникальными элементами (по N/2 в каждый список)
    // -------------------------------------------------------------------------
    for (int i = 0; i < N / 2; ++i) {
        // Добавляем случайную строку в список общих элементов
        // Эти строки позже будут вставлены в оба основных списка
        common.push_back(getRandom(7));
        
        // Добавляем уникальные строки в каждый из списков
        // getRandom(7) генерирует строку длины 7 — достаточно для уникальности
        list1.push_back(getRandom(7));
        list2.push_back(getRandom(7));
    }
    
    // -------------------------------------------------------------------------
    // Шаг 2: Вставка общих элементов в случайные позиции
    // -------------------------------------------------------------------------
    // Для каждого общего элемента:
    for (const auto& c : common) {
        // --- Вставка в list1 ---
        // Выбираем случайную позицию для вставки (от 0 до size()-1)
        int i = rand() % list1.size();
        
        // Проходим по списку с помощью итератора
        // it++ перемещает итератор к следующему элементу
        // i-- уменьшает счётчик; когда i==0, мы на нужной позиции
        for (auto it = list1.begin(); it != list1.end(); ++it, --i) {
            if (i == 0) {
                // insert(it, c) вставляет элемент c ПЕРЕД позицией it
                // Это O(1) для std::list, в отличие от O(N) для std::vector
                list1.insert(it, c);
                break; // Прерываем цикл после успешной вставки
            }
        }
        
        // --- Вставка в list2 (аналогично) ---
        i = rand() % list2.size();
        for (auto it = list2.begin(); it != list2.end(); ++it, --i) {
            if (i == 0) {
                list2.insert(it, c);
                break;
            }
        }
    }
    // После выполнения: каждый список содержит ~N элементов, 
    // из которых ~N/2 — общие для обоих списков
}

//=============================================================================
// ФУНКЦИЯ: intersectNaive
// Назначение: Поиск общих элементов "в лоб" — наивный алгоритм
// Параметры:
//   l1, l2 — входные списки строк
// Возвращает: список строк, присутствующих в обоих входных списках
// Сложность: O(N²) — для каждого элемента l1 выполняется линейный поиск в l2
// Примечание: Прост в реализации, но неэффективен для больших данных
//=============================================================================
list<string> intersectNaive(const list<string>& l1, const list<string>& l2) {
    list<string> result; // Список для хранения найденных общих элементов
    
    // Внешний цикл: перебираем каждый элемент первого списка
    // const auto& s1 — ссылка на константный элемент (копирование не нужно)
    for (const auto& s1 : l1) {
        // Внутренний цикл: ищем текущий элемент s1 во втором списке
        for (const auto& s2 : l2) {
            // Сравнение строк: оператор== для std::string сравнивает содержимое
            if (s1 == s2) {
                // Нашли совпадение — добавляем в результат
                result.push_back(s1);
                
                // break важен: один элемент из l1 может совпасть с несколькими в l2,
                // но нам нужно добавить его в результат только один раз
                break;
            }
        }
    }
    
    return result; // Возвращаем список найденных общих элементов
}

//=============================================================================
// ФУНКЦИЯ: intersectAdvanced
// Назначение: Оптимизированный поиск с предварительной обработкой
// Параметры:
//   l1, l2 — входные списки строк
// Возвращает: список строк, присутствующих в обоих входных списках
// Сложность: O(N) в среднем — благодаря хеш-таблице unordered_set
// Обоснование оптимизации:
//   - unordered_set хранит элементы в хеш-таблице
//   - Поиск элемента в хеш-таблице выполняется в среднем за O(1)
//   - Общая сложность: O(N) на построение таблицы + O(N) на поиск = O(N)
//   - Дополнительная память: O(N) для хранения хеш-таблицы
//=============================================================================
list<string> intersectAdvanced(const list<string>& l1, const list<string>& l2) {
    list<string> result; // Список для результата
    
    // -------------------------------------------------------------------------
    // ПРЕДОБРАБОТКА: Создаём хеш-таблицу из элементов второго списка
    // -------------------------------------------------------------------------
    // Конструктор unordered_set принимает итераторы начала и конца диапазона
    // Время построения: O(N) в среднем, где N = размер l2
    // Память: ~2-3× размер данных из-за коэффициента загрузки хеш-таблицы
    unordered_set<string> lookup(l2.begin(), l2.end());
    
    // -------------------------------------------------------------------------
    // ПОИСК: Проверяем каждый элемент первого списка на наличие в хеш-таблице
    // -------------------------------------------------------------------------
    for (const auto& s1 : l1) {
        // count(key) возвращает 1 если ключ есть, 0 если нет
        // Для unordered_set это операция в среднем O(1) благодаря хешированию
        // В худшем случае (много коллизий) может деградировать до O(N),
        // но при хорошей хеш-функции это маловероятно
        if (lookup.count(s1)) {
            // Элемент найден — добавляем в результат
            result.push_back(s1);
        }
    }
    
    return result;
}

//=============================================================================
// ФУНКЦИЯ: main
// Назначение: Точка входа, управление тестированием и измерением времени
//=============================================================================
int main() {
    // Инициализация генератора случайных чисел
    // time(nullptr) возвращает текущее время в секундах с эпохи Unix
    // static_cast<unsigned> преобразует time_t к unsigned для srand()
    // Без этого rand() будет выдавать одну и ту же последовательность
    srand(static_cast<unsigned>(time(nullptr)));
    
    // -------------------------------------------------------------------------
    // КОНФИГУРАЦИЯ ТЕСТА
    // -------------------------------------------------------------------------
    // N определяет размер тестовых списков
    // Рекомендуется тестировать с разными значениями:
    //   - N = 10: для отладки и проверки корректности
    //   - N = 1000: для оценки производительности на средних данных
    //   - N = 5000: для демонстрации разницы между алгоритмами
    const int N = 5000;
    
    // Объявляем три списка: два основных и один для общих элементов
    list<string> list1, list2, common;
    
    // Генерируем тестовые данные согласно алгоритму из prepareData
    prepareData(N, list1, list2, common);
    
    cout << "Тестирование с N = " << N << " элементов в каждом списке" << endl;
    cout << "Общих элементов для вставки: " << common.size() << endl << endl;
    
    // -------------------------------------------------------------------------
    // ИЗМЕРЕНИЕ ВРЕМЕНИ: Наивный алгоритм
    // -------------------------------------------------------------------------
    // steady_clock — монотонные часы, не подверженные корректировкам времени
    // now() возвращает момент времени типа time_point
    auto start = chrono::steady_clock::now();
    
    // Вызываем наивный алгоритм
    auto resNaive = intersectNaive(list1, list2);
    
    // Замеряем время после выполнения
    auto stop = chrono::steady_clock::now();
    
    // Вычисляем разницу и конвертируем в микросекунды
    // duration_cast<> выполняет безопасное преобразование единиц времени
    // .count() извлекает числовое значение из объекта duration
    auto dtNaive = chrono::duration_cast<chrono::microseconds>(stop - start).count();
    
    // -------------------------------------------------------------------------
    // ИЗМЕРЕНИЕ ВРЕМЕНИ: Оптимизированный алгоритм
    // -------------------------------------------------------------------------
    start = chrono::steady_clock::now();
    auto resAdv = intersectAdvanced(list1, list2);
    stop = chrono::steady_clock::now();
    auto dtAdv = chrono::duration_cast<chrono::microseconds>(stop - start).count();
    
    // -------------------------------------------------------------------------
    // ВЫВОД РЕЗУЛЬТАТОВ
    // -------------------------------------------------------------------------
    cout << "=== Результаты ===" << endl;
    cout << "Наивный алгоритм:" << endl;
    cout << "  Время: " << dtNaive << " мкс" << endl;
    cout << "  Найдено элементов: " << resNaive.size() << endl;
    
    cout << "\nОптимизированный алгоритм:" << endl;
    cout << "  Время: " << dtAdv << " мкс" << endl;
    cout << "  Найдено элементов: " << resAdv.size() << endl;
    
    // Проверка корректности: результаты должны совпадать
    if (resNaive.size() == resAdv.size()) {
        cout << "\n✓ Результаты совпадают — алгоритмы работают корректно" << endl;
    } else {
        cout << "\n✗ ОШИБКА: результаты различаются!" << endl;
    }
    
    // Расчёт ускорения (если оптимизированный алгоритм быстрее)
    if (dtAdv > 0) {
        double speedup = static_cast<double>(dtNaive) / dtAdv;
        cout << "\nУскорение: " << speedup << "x" << endl;
    }
    
    return 0;
}
